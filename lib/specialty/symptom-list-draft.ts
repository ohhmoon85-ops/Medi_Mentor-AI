/** symptom_id로 항목 조회 */
export function findSymptom(id: string) {
  return SYMPTOMS.find((s) => s.symptom_id === id)
}

/** triage_level별 필터 */
export function getByTriageLevel(level: 'critical' | 'urgent' | 'night_weekend' | 'outpatient' | 'self_care') {
  return SYMPTOMS.filter((s) => s.triage_level === level)
}

/** Stage A·B red_flag_category 매핑 항목 조회 */
export function getByRedFlagCategory(category: string) {
  return SYMPTOMS.filter((s) => s.red_flag_category === category)
}
